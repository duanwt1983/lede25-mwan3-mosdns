#!/bin/bash
# Regenerate nginx gw routes (lua + locations) from sites.json and refresh status.
set -euo pipefail

SITES="${SITES_JSON:-/var/www/center-portal/sites.json}"
GW_CONF="${GW_CONF:-/www/server/panel/vhost/nginx/center-portal-gw.inc}"
ROUTES_LUA="${ROUTES_LUA:-/etc/nginx/lua/center-gw-routes.lua}"
STATUS_SH="${STATUS_SH:-/opt/center-portal/center-portal-status.sh}"
NGINX_RELOAD="${NGINX_RELOAD:-/etc/init.d/nginx reload}"

command -v jq >/dev/null 2>&1 || { echo "jq required" >&2; exit 1; }
[ -f "$SITES" ] || { echo "missing $SITES" >&2; exit 1; }

TMP="$(mktemp)"
TMP_LUA="$(mktemp)"

{
  echo "-- Generated by center-portal-sync — do not edit"
  echo "return {"
  jq -c '.sites[]?' "$SITES" | while read -r row; do
    id="$(echo "$row" | jq -r '.id // empty')"
    port="$(echo "$row" | jq -r '.luci_port // empty')"
    host="$(echo "$row" | jq -r '.luci_host // "192.168.9.1"')"
    [ -n "$id" ] || continue
    [ -n "$port" ] || continue
    case "$id" in
      *[!a-zA-Z0-9_-]*)
        echo "skip invalid site id: $id" >&2
        continue
        ;;
    esac
    echo "  [\"${id}\"] = { port = ${port}, host = \"${host}\" },"
  done
  echo "}"
} >"$TMP_LUA"

mv -f "$TMP_LUA" "$ROUTES_LUA"
chmod 644 "$ROUTES_LUA"

cat >"$TMP" <<'NGINX'
# Generated by center-portal-sync — LuCI under /home/gw/<site_id>/ (prefix ^~ beats /home/ alias)
set $gw_port "";
set $gw_host "";
set $gw_pub_prefix "";
set $gw_backend_path "";

location @center_gw_offline {
    internal;
    default_type text/html;
    charset utf-8;
    return 503 '<!DOCTYPE html><html lang="zh-CN"><head><meta charset="utf-8"><title>隧道未连接</title></head><body style="font-family:sans-serif;max-width:36em;margin:2em auto;line-height:1.6"><h1>502/504：门店 frp 隧道未连接</h1><p>中心机 <code>127.0.0.1:映射端口</code> 无响应，通常是门店网关 <strong>frpc 未运行</strong> 或未连上 frps。</p><p>请在网关 LuCI「区域接入中心」确认已导入 CA、启用并<strong>保存并应用</strong>，或 SSH：<code>/usr/libexec/lede-center-frpc apply</code>。</p><p><a href="/home/">返回区域接入中心首页</a></p></body></html>';
}

location ^~ /home/gw/ {
    access_by_lua_file /etc/nginx/lua/center-portal-gw-handler.lua;
    proxy_pass https://127.0.0.1:$gw_port$gw_backend_path$is_args$args;
    proxy_connect_timeout 10s;
    proxy_intercept_errors on;
    error_page 502 504 =503 @center_gw_offline;
    proxy_ssl_verify off;
    proxy_http_version 1.1;
    proxy_set_header Host $gw_host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_redirect ~^https?://[^/]+/(.*)$ https://$http_host$gw_pub_prefix$1;
    proxy_redirect ~^/(.*)$ https://$http_host$gw_pub_prefix$1;
    proxy_buffering on;
    sub_filter_once off;
    sub_filter_types text/html text/css application/javascript application/json;
    sub_filter 'href="/luci-static/' 'href="${gw_pub_prefix}luci-static/';
    sub_filter 'src="/luci-static/' 'src="${gw_pub_prefix}luci-static/';
    sub_filter 'action="/cgi-bin/' 'action="${gw_pub_prefix}cgi-bin/';
    sub_filter '"/cgi-bin/' '"${gw_pub_prefix}cgi-bin/';
    sub_filter 'href="/"' 'href="${gw_pub_prefix}cgi-bin/luci/"';
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
}

# LuCI HTML still references /luci-static/ at site root — use center_gw cookie
location ^~ /cgi-bin/ {
    access_by_lua_file /etc/nginx/lua/center-portal-gw-proxy.lua;
    proxy_pass https://127.0.0.1:$gw_port$request_uri;
    proxy_connect_timeout 10s;
    proxy_intercept_errors on;
    error_page 502 504 =503 @center_gw_offline;
    proxy_ssl_verify off;
    proxy_http_version 1.1;
    proxy_set_header Host $gw_host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_redirect ~^https?://[^/]+/(.*)$ https://$http_host$gw_pub_prefix$1;
    proxy_redirect ~^/(.*)$ https://$http_host$gw_pub_prefix$1;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
}

location ^~ /luci-static/ {
    access_by_lua_file /etc/nginx/lua/center-portal-gw-proxy.lua;
    proxy_pass https://127.0.0.1:$gw_port$request_uri;
    proxy_connect_timeout 10s;
    proxy_intercept_errors on;
    error_page 502 504 =503 @center_gw_offline;
    proxy_ssl_verify off;
    proxy_http_version 1.1;
    proxy_set_header Host $gw_host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
}
NGINX

mv -f "$TMP" "$GW_CONF"
chmod 644 "$GW_CONF"

if [ -x "$STATUS_SH" ]; then
  "$STATUS_SH"
fi

if nginx -t 2>/dev/null; then
  $NGINX_RELOAD
  echo "nginx reloaded; gw -> $GW_CONF routes -> $ROUTES_LUA"
else
  echo "nginx -t failed; gw routes/lua updated but nginx not reloaded:" >&2
  nginx -t 2>&1 >&2 || true
  exit 1
fi
